"""SQLModel table models - single source of truth for the database layer.

Table/column definition follows database/SCHEMA.md v0.2 (owner: Member 3).
Alembic migrations live in `database/` and import `metadata` from this module,
so this file must stay in sync with SCHEMA.md before a migration is generated.

Conventions (database/README.md v0.2):
- snake_case in DB, camelCase in API (mapping is done in app/schemas.py).
- Timestamp is UTC and generated by the Backend, never by the ESP32.
- Sensor failures are stored as NULL, never NaN and never 0.
- Enum-like columns are plain strings with a constrained value set so the same
  schema works on SQLite and PostgreSQL.
"""

