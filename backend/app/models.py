def utcNow() -> datetime:
    """Backend-side UTC clock used for every persisted timestamp.

    Timezone-aware so SQLAlchemy stores it correctly on both SQLite and
    PostgreSQL; the API layer renders it as ISO8601 with a trailing Z.
    """
    return datetime.now(timezone.utc)


class TelemetryReading(SQLModel, table=True):
    """Append-only sensor history received from MQTT topic `telemetry`."""

    __tablename__ = "telemetry_readings"
    __table_args__ = (
        Index("ix_telemetry_device_received", "device_id", "received_at"),
        # Check constraints from database/SCHEMA.md v0.2 section 3. Alembic
        # autogenerate picks them up from this metadata, so the initial
        # migration carries them too.
        CheckConstraint(
            "humidity_pct IS NULL OR (humidity_pct >= 0 AND humidity_pct <= 100)",
            name="ck_telemetry_humidity_range",
        ),
        CheckConstraint(
            "light_lux IS NULL OR light_lux >= 0",
            name="ck_telemetry_light_non_negative",
        ),
    )

    id: int | None = Field(default=None, primary_key=True)
    device_id: str = Field(index=False, max_length=64)
    temperature_c: float | None = Field(default=None)
    humidity_pct: float | None = Field(default=None)
    light_lux: float | None = Field(default=None)
    # true: co nuoc, false: het nuoc, NULL: cam bien khong dang tin cay
    water_ok: bool | None = Field(default=None)
    received_at: datetime = Field(default_factory=utcNow)


class DeviceState(SQLModel, table=True):
    """Latest known real state of a device (topic `state` + `status`)."""

    __tablename__ = "device_states"

    device_id: str = Field(primary_key=True, max_length=64)
    mode: str = Field(default=MODE_AUTO, max_length=16)
    fan: bool = Field(default=False)
    mist: bool = Field(default=False)
    lamp: bool = Field(default=False)
    failsafe_active: bool = Field(default=False)
    online: bool = Field(default=False)
    last_seen_at: datetime | None = Field(default=None)
    last_command_id: str | None = Field(default=None, max_length=64)
    last_command_result: str | None = Field(default=None, max_length=16)
    reason: str | None = Field(default=None, max_length=64)
    updated_at: datetime = Field(default_factory=utcNow)


class CommandLog(SQLModel, table=True):
    """Lifecycle of a MANUAL command: PENDING -> APPLIED/REJECTED/TIMEOUT."""

    __tablename__ = "command_logs"
    __table_args__ = (
        Index("ix_command_device_requested", "device_id", "requested_at"),
        Index("ix_command_status", "status"),
    )

    command_id: str = Field(primary_key=True, max_length=64)
    device_id: str = Field(index=False, max_length=64)
    device: str = Field(index=False, max_length=16)
    requested_on: bool = Field(default=False)
    status: str = Field(default=COMMAND_PENDING, max_length=16)
    reason: str | None = Field(default=None, max_length=64)
    requested_at: datetime = Field(default_factory=utcNow)
    completed_at: datetime | None = Field(default=None)


class Alert(SQLModel, table=True):
    """Alert history derived by the Backend; deduplicated per device + code."""

    __tablename__ = "alerts"
    __table_args__ = (
        Index("ix_alert_device_started", "device_id", "started_at"),
        Index("ix_alert_device_active", "device_id", "active"),
    )

    id: int | None = Field(default=None, primary_key=True)
    device_id: str = Field(index=False, max_length=64)
    code: str = Field(index=False, max_length=32)
    severity: str = Field(default=SEVERITY_WARNING, max_length=16)
    message: str = Field(default="")
    active: bool = Field(default=True)
    started_at: datetime = Field(default_factory=utcNow)
    last_seen_at: datetime = Field(default_factory=utcNow)
    resolved_at: datetime | None = Field(default=None)


class DeviceConfig(SQLModel, table=True):
    """Latest desired configuration received from the Dashboard.

    Storing a row does not prove the ESP32 applied it: the firmware has no
    `configId` acknowledgement yet, so `POST /api/config` only returns
    PUBLISHED (contract section 3.7).
    """

    __tablename__ = "device_configs"

    device_id: str = Field(primary_key=True, max_length=64)
    mode: str = Field(default=MODE_AUTO, max_length=16)
    temp_on_c: float = Field(default=30.0)
    temp_off_c: float = Field(default=28.0)
    humidity_on_pct: float = Field(default=55.0)
    humidity_off_pct: float = Field(default=65.0)
    light_on_lux: float = Field(default=300.0)
    light_off_lux: float = Field(default=700.0)
    updated_at: datetime = Field(default_factory=utcNow)
    published_at: datetime | None = Field(default=None)

